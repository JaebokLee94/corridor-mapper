/** Compile the fixed presentation formulas with MathJax, without shipping a typesetter or fonts.
 * SVG glyph paths are self-contained; fontCache:none also prevents cross-formula ID collisions.
 * Input: authored data-tex labels and optional DOM_TEX/CANVAS_TEX lists. Output: deterministic SVGs.
 */
import { readFile, writeFile, access } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { runInNewContext } from 'node:vm';
import { mathjax } from 'mathjax-full/js/mathjax.js';
import { TeX } from 'mathjax-full/js/input/tex.js';
import { SVG } from 'mathjax-full/js/output/svg.js';
import { liteAdaptor } from 'mathjax-full/js/adaptors/liteAdaptor.js';
import { RegisterHTMLHandler } from 'mathjax-full/js/handlers/html.js';
import 'mathjax-full/js/input/tex/ams/AmsConfiguration.js';

const root = new URL('./', import.meta.url);
const adaptor = liteAdaptor();
RegisterHTMLHandler(adaptor);
const document = mathjax.document('', {
  InputJax: new TeX({ packages: ['base', 'ams'], formatError: (_jax, error) => { throw new Error(error.message); } }),
  OutputJax: new SVG({ fontCache: 'none' }),
});
export function compileTex(tex) {
  const container = document.convert(tex, { display: false });
  let svg = adaptor.outerHTML(adaptor.firstChild(container));
  if (/data-mml-node="merror"|<text[\s>]|<image[\s>]|(?:href|src)=/u.test(svg))
    throw new Error(`Formula did not compile to self-contained glyph paths: ${tex}`);
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1].split(/\s+/).map(Number);
  if (!viewBox || viewBox.length !== 4 || !viewBox.every(Number.isFinite)) throw new Error(`Missing SVG bounds: ${tex}`);
  const [, top, width, height] = viewBox;
  const depth = Math.max(0, top + height) / 1000;
  svg = svg.replace(/^<svg\b[^>]*>/, tag => tag.replace(/\s(?:width|height|style|role|focusable)="[^"]*"/g, ''));
  svg = svg.replace('<svg ', '<svg aria-hidden="true" focusable="false" ');
  return { width: width / 1000, height: height / 1000, depth, svg };
}
export async function buildLatex() {
  const html = await readFile(new URL('drf.html', root), 'utf8');
  const decode = value => value.replace(/&quot;/g, '\"').replace(/&apos;/g, "'").replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');
  const tex = new Set([...html.matchAll(/data-tex="([^"]*)"/g)].map(match => decode(match[1])));
  for (const [filename, key] of [['drf/dom-math.mjs', 'DOM_TEX'], ['drf/render-math.mjs', 'CANVAS_TEX']]) {
    const url = new URL(filename, root);
    try { await access(url); } catch { continue; }
    const source = await readFile(url, 'utf8');
    const expression = source.match(new RegExp(`export const ${key} = (\\[[\\s\\S]*?\\]);`))?.[1];
    if (!expression) throw new TypeError(`${filename} must export a literal ${key} array`);
    const registry = runInNewContext(expression, {}, { timeout: 100 });
    if (!Array.isArray(registry)) throw new TypeError(`${filename} must export ${key}`);
    registry.forEach(value => tex.add(value));
  }
  const assets = Object.fromEntries([...tex].sort().map(source => [source, compileTex(source)]));
  const output = '// Generated by node build-latex.mjs from authored LaTeX. MathJax 3.2.2, SVG path output.\n'
    + '// Do not hand-edit. No external fonts, images or runtime typesetter are required.\n'
    + `export const LATEX_ASSETS = ${JSON.stringify(assets, null, 2)};\n`;
  await writeFile(new URL('drf/latex-assets.mjs', root), output);
  return Object.keys(assets).length;
}
if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url)
  console.log(`Compiled ${await buildLatex()} LaTeX expressions to drf/latex-assets.mjs`);
