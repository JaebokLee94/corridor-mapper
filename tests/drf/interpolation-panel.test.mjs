import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {JSDOM} from 'jsdom';

test('interpolation panel follows method and geometry without changing raw recall',async()=>{
  const {renderInterpolationPanel}=await import('../../drf/interpolation-panel.mjs');
  const {window}=new JSDOM(readFileSync(new URL('../../drf.html',import.meta.url),'utf8'));
  const $=id=>window.document.getElementById(id),fmt=(value,places)=>value.toFixed(places);
  const frame={methods:{guarded:{recall:.5,missing:5,interpolation:{recall:.7,missing:3,hermite:{recall:.8,missing:2}}},baseline:{recall:.4,missing:6,interpolation:{recall:.6,missing:4}}}};
  const render=(mode,kind='linear',f=frame)=>renderInterpolationPanel($,mode,kind,f,fmt);
  const recalls=()=>Array.from($('interpolationMetrics').querySelector('[data-metric="recall"]').cells).slice(1).map(c=>c.textContent);
  render('guarded');assert.deepEqual(recalls(),['70.0','50.0']);assert.equal($('historyFirst').textContent,'Linear');assert.equal($('historySecond').textContent,'Raw map');assert.deepEqual(Array.from($('interpolationMetrics').tHead.rows[0].cells,c=>c.textContent),['Metric','Linear','Raw map']);assert.equal($('methodMetrics').hidden,true);
  const selector=$('interpolationChartMetric');
  assert.equal(selector.hidden,false);
  assert.equal(selector.value,'mapF1'); assert.equal($('historyMetric').value,'mapF1');
  assert.equal($('interpolationMetrics').tBodies[0].rows[0].dataset.metric,'mapF1');
  assert.equal($('methodMetrics').tBodies[0].rows[0].cells[1].id,'mapF1Value');
  assert.deepEqual(Array.from(selector.options,o=>o.value),Array.from($('interpolationMetrics').tBodies[0].rows,r=>r.dataset.metric));
  selector.value='count';
  render('guarded','hermite');assert.deepEqual(recalls(),['80.0','50.0']);
  assert.equal($('historyFirst').textContent,'Gap Hermite');
  render('baseline');assert.equal($('historyFirst').textContent,'Linear');assert.deepEqual(recalls(),['60.0','40.0']);
  const e=frame.methods.guarded.interpolation;
  e.centre={recall:.3,missing:7,count:1,lengthM:4}; e.rawMap={recall:.5,missing:5,count:0,lengthM:6};
  render('guarded','centre');assert.deepEqual(recalls(),['30.0','50.0']);assert.equal(selector.selectedOptions[0].textContent,'Centre links');
  assert.equal($('interpolationMetrics').querySelector('[data-metric="lengthM"]').cells[0].textContent,'Map length m');
  render('guarded','linear');assert.equal(selector.selectedOptions[0].textContent,'Gaps joined');
  assert.equal($('interpolationMetrics').querySelector('[data-metric="lengthM"]').cells[0].querySelector('small').textContent,'m');
  render('baseline','hermite');assert.deepEqual(recalls(),['—','40.0']);
  render('guarded','linear',null);assert.deepEqual(recalls(),['—','—']);
  render('compare');assert.equal($('interpolationMetrics').hidden,true);assert.equal($('methodMetrics').hidden,false);assert.equal($('historySecond').textContent,'WM-F');assert.equal($('historyMetric').hidden,false);
  assert.equal(selector.hidden,true);
  render('baseline');
  assert.equal(selector.value,'count');
  assert.match($('metricChart').getAttribute('aria-label'),/WM-F Gaps joined/);
  window.close();
});
